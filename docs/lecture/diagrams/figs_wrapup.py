def rich(x, y, parts, size=B, anchor="start") -> str:
    """色や太さを途中で変える1行の文字。parts は [(文字, 色, 太字), …]（色・太字は省ける）"""
    spans = ""
    for p in parts:
        s, color, bold = (p + (None, False))[:3] if isinstance(p, tuple) else (p, None, False)
        a = (f" fill='{color}'" if color else "") + (" font-weight='700'" if bold else "")
        spans += f"<tspan{a}>{escape(s)}</tspan>"
    return f"<text x='{x}' y='{y}' font-size='{size}' fill='{INK}' text-anchor='{anchor}'>{spans}</text>"


