def rule(x1, y1, x2, y2, color=LINE, width=3) -> str:
    """区切りの線"""
    return f"<line x1='{x1}' y1='{y1}' x2='{x2}' y2='{y2}' stroke='{color}' stroke-width='{width}'/>"


def tag(x, y, s, color, anchor="middle") -> str:
    """矢印の名前（28px の太字）"""
    return text(x, y, s, 28, color, True, anchor)


